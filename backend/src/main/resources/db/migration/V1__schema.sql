-- Upstream db.ts schema (SQLite) ported to Postgres, plus Elo/duels and tenancy.
-- Timestamps stay text 'YYYY-MM-DD HH:MM:SS' in UTC, exactly what SQLite's datetime('now') wrote,
-- so the JSON the API returns is unchanged. JSON columns stay text: jsonb would reorder keys.

-- UTC now minus n days, in the stored text format.
CREATE FUNCTION utc_text(n int DEFAULT 0) RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char((now() AT TIME ZONE 'UTC') - make_interval(days => n), 'YYYY-MM-DD HH24:MI:SS') $$;

-- One person = one tenant ('local' when ideagen.auth=none). Logins are (provider, subject).
CREATE TABLE tenants (
  id text PRIMARY KEY,
  name text NOT NULL DEFAULT '',
  email text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE identities (
  provider text NOT NULL,
  subject text NOT NULL,
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  email text,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (provider, subject)
);
CREATE INDEX identities_tenant ON identities(tenant_id);
-- Non-secret app settings as JSON (models, base URLs, budget, folders).
CREATE TABLE tenant_settings (
  tenant_id text PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  settings text NOT NULL DEFAULT '{}',
  updated_at timestamptz NOT NULL DEFAULT now()
);
-- Provider API keys and the AI Scientist key, Tink AEAD; associated data = tenant_id || ':' || name.
CREATE TABLE tenant_secrets (
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name text NOT NULL,
  ciphertext bytea NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, name)
);

CREATE TABLE templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name text NOT NULL,
  system text NOT NULL,
  expand text NOT NULL,
  combine text NOT NULL,
  sort integer NOT NULL DEFAULT 0
);
CREATE INDEX templates_tenant ON templates(tenant_id);
CREATE TABLE boards (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  title text NOT NULL,
  goal text NOT NULL DEFAULT '',
  config text NOT NULL DEFAULT '{}',
  origin_idea_id bigint,
  summary text,
  created_at text NOT NULL DEFAULT utc_text(),
  updated_at text NOT NULL DEFAULT utc_text()
);
CREATE INDEX boards_tenant ON boards(tenant_id);
CREATE TABLE ideas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id bigint NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
  title text NOT NULL,
  pitch text NOT NULL DEFAULT '',
  kind text NOT NULL CHECK (kind IN ('seed', 'expand', 'combine', 'guest')),
  source_url text,
  x double precision NOT NULL DEFAULT 0,
  y double precision NOT NULL DEFAULT 0,
  originality integer,
  feasibility integer,
  impact integer,
  reason text,
  judged_at text,
  medal_override integer,
  generation integer NOT NULL DEFAULT 0,
  project_path text,
  origin_idea_id bigint REFERENCES ideas(id) ON DELETE SET NULL,
  origin_board_id bigint REFERENCES boards(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT utc_text(),
  -- Elo from pairwise duels (added after upstream)
  elo double precision,
  duels integer NOT NULL DEFAULT 0
);
ALTER TABLE boards ADD FOREIGN KEY (origin_idea_id) REFERENCES ideas(id) ON DELETE SET NULL;
CREATE INDEX ideas_board ON ideas(board_id);
CREATE UNIQUE INDEX ideas_guest_once ON ideas(board_id, origin_idea_id) WHERE origin_idea_id IS NOT NULL;
CREATE TABLE edges (
  seq bigint GENERATED ALWAYS AS IDENTITY, -- insertion order (SQLite's rowid)
  board_id bigint NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
  from_id bigint NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,
  to_id bigint NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,
  PRIMARY KEY (from_id, to_id)
);
CREATE INDEX edges_board ON edges(board_id);
CREATE INDEX edges_to ON edges(to_id);
CREATE TABLE leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id bigint NOT NULL REFERENCES boards(id) ON DELETE CASCADE,
  source text NOT NULL CHECK (source IN ('x', 'research')),
  title text NOT NULL,
  summary text NOT NULL DEFAULT '',
  hook text NOT NULL DEFAULT '',
  url text,
  meta text NOT NULL DEFAULT '{}',
  idea_id bigint REFERENCES ideas(id) ON DELETE SET NULL,
  fetched_at text NOT NULL DEFAULT utc_text()
);
CREATE INDEX leads_board ON leads(board_id);
-- Keywords come from the judge, in one canonical form, so trends can be counted across boards.
CREATE TABLE idea_keywords (
  idea_id bigint NOT NULL REFERENCES ideas(id) ON DELETE CASCADE,
  keyword text NOT NULL,
  PRIMARY KEY (idea_id, keyword)
);
CREATE INDEX idea_keywords_kw ON idea_keywords(keyword);
-- Saved cross-board syntheses for the report window (latest one per tenant is shown).
CREATE TABLE reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  days integer NOT NULL,
  lang text NOT NULL,
  content text NOT NULL,
  created_at text NOT NULL DEFAULT utc_text()
);
CREATE INDEX reports_tenant ON reports(tenant_id, id);
-- Spend ledger per tenant, board and local calendar day; the rate limiter reads it.
-- board_id 0 = spend that belongs to no board (report synthesis).
CREATE TABLE spend (
  tenant_id text NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  board_id bigint NOT NULL,
  day text NOT NULL,
  usd double precision NOT NULL DEFAULT 0,
  calls integer NOT NULL DEFAULT 0,
  PRIMARY KEY (tenant_id, board_id, day)
);
